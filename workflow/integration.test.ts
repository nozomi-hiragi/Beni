import {test,expect} from 'bun:test';
import {Store} from '../store';
import {Workflow,RequirementsGeneration} from './index';
import {PlanGeneration} from './plan';
import {ExecutionReview} from './review';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';

test('persistent instruction to generation, approval, execution and corrective execution trace',async()=>{
 const dir=mkdtempSync(join(tmpdir(),'beni-integration-')),path=join(dir,'db');
 let store=new Store(path),workflow=new Workflow(path),generation=new RequirementsGeneration(path),planning=new PlanGeneration(path),reviewing=new ExecutionReview(path);
 try{
  store.createProject('demo','/tmp/demo');store.createTask(1,'login');
  const instructionId=workflow.recordInstruction(1,'Build a login form');
  const generated=await generation.generate(1,'initial-spec',{generate:async snapshot=>({content:'# Login\n'+snapshot.instructions.map(i=>i.content).join('\n')})});
  expect(generated.version).toBe(2);
  const instruction=workflow.events(1).find(e=>e.id===instructionId)!;
  expect(instruction.payload.original).toBe('Build a login form');
  expect(generation.history(1)[0].payload.snapshot.instructions[0].id).toBe(instruction.payload.messageId);
  const initialPlan=await planning.generate(1,'initial-plan',{generate:async snapshot=>{expect(snapshot.requirements.version).toBe(2);return {content:'Implement the login form'}}});
  expect(initialPlan.status).toBe('adopted');
  const planVersion=initialPlan.version!;
  const approvalId=workflow.approve(1,2,planVersion,'user');
  const first=await workflow.execute(1,{execute:async snapshot=>({output:'Form implemented',evidence:['fake-test: initial form; spec '+snapshot.requirements.version]})});
  const rejected=await reviewing.review(1,first.attemptId,{review:async()=>({passed:false,feedback:'Add a password visibility toggle test'})});
  expect(rejected.status).toBe('changes_requested');
  expect(()=>workflow.approve(1,2,planVersion,'user')).toThrow('Review requires a new plan');
  const feedbackId=workflow.feedback(1,first.attemptId,'Add a password visibility toggle');
  workflow.close();generation.close();planning.close();reviewing.close();store.close();
  store=new Store(path);workflow=new Workflow(path);generation=new RequirementsGeneration(path);planning=new PlanGeneration(path);reviewing=new ExecutionReview(path);
  await expect(workflow.execute(1,{execute:async()=>{throw Error('must not run')}})).rejects.toThrow('Current approval required');
  expect(()=>workflow.approve(1,2,planVersion,'user')).toThrow('Plan must be regenerated');
  const revised=await generation.generate(1,'revised-spec',{generate:async snapshot=>({content:snapshot.document.content+'\n'+snapshot.instructions.at(-1)!.content})});
  expect(revised.version).toBe(3);
  const revisedPlan=await planning.generate(1,'revised-plan',{generate:async snapshot=>{expect(snapshot.requirements.version).toBe(3);expect(snapshot.previousPlan?.version).toBe(planVersion);expect(snapshot.reviewFeedback[0].reviewId).toBe(rejected.reviewId);expect(snapshot.reviewFeedback[0].attemptId).toBe(first.attemptId);expect(snapshot.reviewFeedback[0].content).toBe('Add a password visibility toggle test');return {content:'Implement the visibility toggle'}}});
  expect(revisedPlan.status).toBe('adopted');
  const newPlan=revisedPlan.version!;
  const newApproval=workflow.approve(1,3,newPlan,'user');
  const corrected=await workflow.execute(1,{execute:async snapshot=>({output:'Visibility toggle implemented',evidence:['fake-test: toggle; plan '+snapshot.plan.version]})});
  const accepted=await reviewing.review(1,corrected.attemptId,{review:async snapshot=>({passed:true,feedback:'Checked visibility toggle evidence: '+snapshot.execution.evidence[0]})});
  expect(accepted.status).toBe('completed');
  expect(reviewing.history(1).map(r=>r.attempt_id)).toEqual([first.attemptId,corrected.attemptId]);
  const events=workflow.events(1),feedback=events.find(e=>e.id===feedbackId)!;
  const requests=events.filter(e=>e.kind==='execution_requested');
  expect(requests[0].payload.approvalId).toBe(approvalId);
  expect(requests[0].payload.attemptId).toBe(first.attemptId);
  expect(feedback.payload.attemptId).toBe(first.attemptId);
  expect(feedback.payload.content).toBe('Add a password visibility toggle');
  const latestPlan=events.filter(e=>e.kind==='plan').at(-1)!;
  expect(latestPlan.payload.messageId).toBe(feedback.payload.messageId);
  expect(latestPlan.payload.requirementsVersion).toBe(3);
  expect(latestPlan.payload.planVersion).toBe(newPlan);
  expect(requests[1].payload.approvalId).toBe(newApproval);
  expect(requests[1].payload.attemptId).toBe(corrected.attemptId);
  expect(requests[1].payload.messageId).toBe(feedback.payload.messageId);
  const results=events.filter(e=>e.kind==='execution_result');
  expect(results.map(e=>e.payload.attemptId)).toEqual([first.attemptId,corrected.attemptId]);
  expect(results.every(e=>e.payload.status==='succeeded'&&!e.payload.stale)).toBe(true);
  expect(generation.history(1).filter(e=>e.kind==='settled').map(e=>e.payload.version)).toEqual([2,3]);
  expect(planning.history(1).filter(e=>e.kind==='settled').map(e=>e.payload.version)).toEqual([1,2]);
  expect(planning.history(1).filter(e=>e.kind==='started').at(-1)!.payload.snapshot.instructions.at(-1).id).toBe(feedback.payload.messageId);
  expect((store.documents(1) as any[]).filter(d=>d.kind==='requirements').map(d=>d.version)).toEqual([1,2,3]);
 }finally{workflow.close();generation.close();planning.close();reviewing.close();store.close();rmSync(dir,{recursive:true,force:true})}
});
